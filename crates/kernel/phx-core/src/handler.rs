/// A stream opened on a traced chunk: its name and subject.
pub type Opened = (&'static str, u64);

/// What the day gives every handler's context: the register, and the state its own system compiled at assembly,
/// which only that system's handlers are given; `opens` is present on a traced chunk.
#[derive(Debug)]
pub struct CtxParts<'a, S: FactStore + ?Sized> {
    pub day: Day,
    pub date: Date,
    pub streams: &'a Streams,
    pub register: &'a Register,
    pub own: &'a (dyn Any + Send + Sync),
    pub facts: &'a mut S,
    pub goods: &'a dyn GoodsView,
    pub intents: &'a mut Intents,
    pub bindings: &'a mut Bindings,
    pub rules: &'a RuleTable,
    pub queue: &'a mut PlayerQueue,
    pub opens: Option<&'a mut Vec<Opened>>,
    /// The chunk's flow buffer, in a sub-step whose flows the day settles.
    pub flows: Option<&'a mut Vec<Flow>>,
}

/// A handler's context, granting exactly what its declaration lists: reading an undeclared fact, writing an undeclared
/// column, emitting an undeclared intent or drawing from an undeclared stream does not compile.
#[clause("TIME.6")]
#[derive(Debug)]
pub struct Ctx<'a, H: HandlerDecl, S: FactStore + ?Sized> {
    parts: CtxParts<'a, S>,
    handler: PhantomData<H>,
}

impl<'a, H: HandlerDecl, S: FactStore + ?Sized> Ctx<'a, H, S> {
    #[doc(hidden)]
    #[must_use]
    pub fn new(parts: CtxParts<'a, S>) -> Ctx<'a, H, S> {
        Ctx { parts, handler: PhantomData }
    }

    pub fn day(&self) -> Day {
        self.parts.day
    }

    /// The day's civil date.
    pub fn date(&self) -> Date {
        self.parts.date
    }

    #[must_use]
    pub fn substep(&self) -> SubStep {
        H::SUBSTEP
    }

    pub fn read<F: FactDef>(&mut self, slot: Slot) -> Missing<i64>
    where
        H: Reads<F>,
    {
        self.parts.facts.read(F::ITEM.name, slot)
    }

    pub fn write<F: FactDef>(&mut self, slot: Slot, value: i64)
    where
        H: Writes<F>,
    {
        self.parts.facts.write(F::ITEM.name, slot, value);
    }

    /// The row's party's free units of a good at its place: what it holds less what is pledged or committed.
    #[must_use]
    pub fn held(&self, slot: Slot, product: u16, grade: u8) -> i64 {
        self.parts.goods.held(slot, product, grade)
    }

    /// Every good the row's party holds at its place.
    #[must_use]
    pub fn goods(&self, slot: Slot) -> &[HeldGood] {
        self.parts.goods.goods(slot)
    }

    /// The plant a row holds, by kind and condition class.
    #[must_use]
    pub fn plant(&self, slot: Slot) -> &[HeldPlant] {
        self.parts.goods.plant(slot)
    }

    /// What winding the row's party down would return.
    pub fn net_assets(&self, slot: Slot) -> Missing<i64> {
        self.parts.goods.net_assets(slot)
    }

    /// The other places a good is marked at and the carriage from the row's place to them, as the public prices show.
    #[must_use]
    pub fn away(&self, slot: Slot, product: u16, grade: u8) -> Vec<Away> {
        self.parts.goods.away(slot, product, grade)
    }

    /// The public outlook of a good's price at the row's place by a method, in its market's raw price.
    pub fn outlook(&self, slot: Slot, product: u16, grade: u8, method: u16) -> Missing<i64> {
        self.parts.goods.outlook(slot, product, grade, method)
    }

    /// The deposits whose rights the row's party holds.
    #[must_use]
    pub fn rights(&self, slot: Slot) -> &[HeldRight] {
        self.parts.goods.rights(slot)
    }

    /// The units of a product, of every grade, the row's party has delivered since the world opened.
    #[must_use]
    pub fn delivered(&self, slot: Slot, product: u16) -> i64 {
        self.parts.goods.delivered(slot, product)
    }

    /// The money the row's party holds on its account.
    pub fn money(&self, slot: Slot) -> Missing<i64> {
        self.parts.goods.money(slot)
    }

    /// The hours a week the row's party's employees work for it.
    pub fn staff_hours(&self, slot: Slot) -> Missing<i64> {
        self.parts.goods.staff_hours(slot)
    }

    /// The country the row stands in.
    pub fn country(&self, slot: Slot) -> Missing<phx_id::CountryId> {
        self.parts.goods.country(slot)
    }

    /// Whether the good's market where the row stands last met with no seller.
    #[must_use]
    pub fn unsold(&self, slot: Slot, product: u16, grade: u8) -> bool {
        self.parts.goods.unsold(slot, product, grade)
    }

    /// The grade classes a product is marked in at some place, in their order.
    #[must_use]
    pub fn grades(&self, product: u16) -> Vec<u8> {
        self.parts.goods.grades(product)
    }

    /// The zone the row stands in.
    pub fn zone(&self, slot: Slot) -> Missing<u32> {
        self.parts.goods.zone(slot)
    }

    /// The goods the row holds at other places than its own.
    #[must_use]
    pub fn elsewhere(&self, slot: Slot) -> &[HeldAway] {
        self.parts.goods.elsewhere(slot)
    }

    /// A good's latest mark at the row's place, in its market's raw price.
    pub fn mark(&self, slot: Slot, product: u16, grade: u8) -> Missing<i64> {
        self.parts.goods.mark(slot, product, grade)
    }

    pub fn posted(&self, slot: Slot, product: u16) -> Missing<i64> {
        self.parts.goods.posted(slot, product)
    }

    pub fn record(&self, slot: Slot, product: u16, method: u16) -> Missing<i64> {
        self.parts.goods.record(slot, product, method)
    }

    pub fn party(&self, slot: Slot) -> Missing<phx_id::PartyId> {
        self.parts.goods.party(slot)
    }

    pub fn emit<I: IntentDef>(&mut self, intent: &I)
    where
        H: Emits<I>,
    {
        self.parts.intents.push(intent);
    }

    /// A flow for a reason the handler declares: from the payer to the payee, an amount of a denomination, from a
    /// source the reason names, in the reason's payment order. A flow runs from its payer, so a negative amount is
    /// refused.
    pub fn flow<R: ReasonDef>(&mut self, sides: [PartyKey; 2], amount: i64, denomination: Denom, source: u32)
    where
        H: Pays<R>,
    {
        if amount < 0 {
            violation!(clause = "Law 5", "a flow of a negative amount", amount = amount);
        }
        let Some(buf) = self.parts.flows.as_deref_mut() else {
            violation!(clause = "TIME.6", "a flow made in a sub-step that settles none");
        };
        let [from, to] = sides;
        buf.push(Flow { payer: from, payee: to, amount, source, denomination, reason: R::CODE, order: R::ORDER });
    }

    /// The register, whose primitives a handler reads through the handles its system keeps.
    #[must_use]
    pub fn register(&self) -> &'a Register {
        self.parts.register
    }

    /// The state the handler's own system compiled at assembly.
    #[must_use]
    pub fn own<T: Any>(&self) -> &'a T {
        let Some(own) = self.parts.own.downcast_ref::<T>() else {
            violation!(clause = "Law 4", "a handler reading state its system did not compile");
        };
        own
    }

    /// The stream's draws for a subject at this day and sub-step; the observer's streams are never the world's.
    #[must_use]
    pub fn draws<T: StreamDef>(&mut self, subject: Subject) -> Draws
    where
        H: DrawsFrom<T>,
    {
        if T::DECL.purpose == Purpose::Observer {
            violation!(clause = "Law 17", "a handler drawing from the observer's stream");
        }
        if let Some(opens) = self.parts.opens.as_deref_mut() {
            opens.push((T::DECL.name, subject.raw()));
        }
        if T::DECL.keyed {
            return self.parts.streams.open_keyed(&T::DECL, subject);
        }
        self.parts.streams.open(&T::DECL, subject, self.parts.day, H::SUBSTEP.ordinal())
    }

    /// What a limit left of a want, recording the binding the party will see when there was an excess.
    pub fn bound<T: Limited>(&mut self, party: PartyId, bound: Bound<T>) -> T {
        self.parts.bindings.take(party, self.parts.day, bound)
    }

    /// A rule handle's answer.
    pub fn rule<I: 'static, O: 'static>(&self, sig: RuleSig<I, O>, input: &I) -> O {
        self.parts.rules.call(sig, input)
    }

    /// A party's decision at a point: the player's queued intent, the rule, or none.
    pub fn decide<I, O: QueuedPayload>(
        &mut self,
        point: &DecisionPointDecl<I, O>,
        party: PartyId,
        decider: Decider,
        input: &I,
    ) -> Option<O> {
        let queued = match decider {
            Decider::Player { .. } => self.parts.queue.take(party, point.name),
            Decider::Rule => None,
        };
        dispatch(point, decider, queued.as_deref(), input)
    }
}

