/// A handler's body over one chunk: its context built from the day's parts, then the body for each row of the chunk.
pub type RunChunk = fn(CtxParts<'_, dyn FactStore>, core::ops::Range<u32>);

/// A handler's declaration, generated by `declare_handler!`: its sub-step, its table, by name what it reads, writes
/// directly, emits and draws, which the marker traits below repeat as types, and its body.
pub trait HandlerDecl: 'static {
    const NAME: &'static str;
    const SUBSTEP: SubStep;
    const TABLE: &'static str;
    const READS: &'static [&'static str];
    const WRITES: &'static [&'static str];
    const INTENTS: &'static [&'static str];
    const STREAMS: &'static [&'static str];
    const CLAUSE: &'static str;
    const RUN: Missing<RunChunk>;
}

/// The handler reads the fact.
pub trait Reads<F: FactDef> {}
/// The handler writes the fact on its own rows, directly.
pub trait Writes<F: FactDef> {}
/// The handler emits the intent, applied at its sub-step's apply point.
pub trait Emits<I: IntentDef> {}
/// The handler draws from the stream.
pub trait DrawsFrom<S: StreamDef> {}

/// A reason money or units move for, declared once: the code its flows carry, which says the lines they post to, and
/// the payment order a payer's flows of it keep among its others.
#[clause("MON.5", "SET.4")]
pub trait ReasonDef: 'static {
    const CODE: u8;
    const ORDER: u8;
}

/// A handler that pays for a reason: its context makes flows of that reason and of no other.
pub trait Pays<R: ReasonDef> {}

/// An effect on anything but the handler's own directly written columns, gathered and applied at the apply point.
pub trait IntentDef {
    const NAME: &'static str;
    fn encode(&self, out: &mut Vec<u64>);
}

/// A handler's intents, in the order it emitted them: each its kind and its words.
#[derive(Debug, Default)]
pub struct Intents {
    words: Vec<u64>,
    items: Vec<(&'static str, usize, usize)>,
}

impl Intents {
    fn push<I: IntentDef>(&mut self, intent: &I) {
        let start = self.words.len();
        intent.encode(&mut self.words);
        self.items.push((I::NAME, start, self.words.len() - start));
    }

    /// Another's intents after these, in their order.
    pub fn append(&mut self, other: Intents) {
        let shift = self.words.len();
        self.words.extend(other.words);
        self.items.extend(other.items.into_iter().map(|(name, start, len)| (name, start + shift, len)));
    }

    /// Each intent's kind and words, in emission order.
    pub fn iter(&self) -> impl Iterator<Item = (&'static str, &[u64])> + '_ {
        self.items.iter().filter_map(|(name, start, len)| self.words.get(*start..start + len).map(|w| (*name, w)))
    }

    #[must_use]
    pub fn len(&self) -> usize {
        self.items.len()
    }

    #[must_use]
    pub fn is_empty(&self) -> bool {
        self.items.is_empty()
    }
}

/// The rows a handler sees: their facts at the sub-step's start, and the handler's own direct writes. A read takes the
/// store mutably so that a traced chunk can record what it read.
pub trait FactStore {
    fn read(&mut self, fact: &'static str, slot: Slot) -> Missing<i64>;
    fn write(&mut self, fact: &'static str, slot: Slot, value: i64);
}

/// A table's facts read without recording the read, as rows visited on the pool read them.
pub trait FactRead: Sync {
    fn peek(&self, fact: &'static str, slot: Slot) -> Missing<i64>;
}

/// A shard of a visit's rows: the facts its handler declares, read from the table before it runs, and the handler's
/// writes kept aside, a row reading back what it wrote, until they are written to the table in the rows' order once
/// every shard has run. A row reads and writes only its own declared facts, so no shard sees another's writes.
#[derive(Debug)]
pub struct FactOverlay {
    facts: Vec<&'static str>,
    slots: Vec<Slot>,
    values: Vec<Missing<i64>>,
    writes: Vec<(Slot, &'static str, i64)>,
}

impl FactOverlay {
    /// The declared `facts` of the rows at `slots`, in the slots' order, read from `base`.
    #[must_use]
    pub fn read_from(base: &dyn FactRead, facts: Vec<&'static str>, slots: &[Slot]) -> FactOverlay {
        let values = slots.iter().flat_map(|s| facts.iter().map(move |f| base.peek(f, *s))).collect();
        FactOverlay { facts, slots: slots.to_vec(), values, writes: Vec::new() }
    }

    /// The writes kept, in the order they were made.
    #[must_use]
    pub fn into_writes(self) -> Vec<(Slot, &'static str, i64)> {
        self.writes
    }

    fn at(&self, fact: &'static str, slot: Slot) -> usize {
        let (Ok(row), Some(f)) = (self.slots.binary_search(&slot), self.facts.iter().position(|x| *x == fact)) else {
            violation!(
                clause = "TIME.6",
                "a handler on the pool read a row or fact outside its shard's",
                slot = slot.get()
            );
        };
        row * self.facts.len() + f
    }
}

impl FactStore for FactOverlay {
    fn read(&mut self, fact: &'static str, slot: Slot) -> Missing<i64> {
        let at = self.at(fact, slot);
        self.values.get(at).copied().unwrap_or(Missing::Absent)
    }

    fn write(&mut self, fact: &'static str, slot: Slot, value: i64) {
        let at = self.at(fact, slot);
        if let Some(v) = self.values.get_mut(at) {
            *v = Missing::Present(value);
        }
        self.writes.push((slot, fact, value));
    }
}

/// A deposit whose right a row's party holds, as the holder sees it: the deposit's place in the map's list, the
/// product extracted from it, the zone its goods stand at once taken, its grade in thousandths, and what it held at the
/// opening and holds still, none for a deposit without end.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct HeldRight {
    pub deposit: u32,
    pub product: u16,
    pub zone: u32,
    pub grade: i64,
    pub opening: Missing<i64>,
    pub remaining: Missing<i64>,
}

/// A good a row holds: its product, its grade class and its units.
pub type HeldGood = (u16, u8, i64);

/// Plant a row holds: its kind, its condition class and its units.
pub type HeldPlant = (u8, u8, i64);

/// A good a row holds at another place than its own: its product, its grade class, the zone, its units there, and
/// those free of other claims, as goods on their way are not.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct HeldAway {
    pub product: u16,
    pub grade: u8,
    pub zone: u32,
    pub units: i64,
    pub free: i64,
}

/// A place a good could be carried to or bought at from where a row stands, as the public prices show it: the zone,
/// the mode, the metres between, the good's mark there for a lot, and the freight of a lot of the good by the mode
/// from the row's place to there at the lowest price carriage is posted at here, and from there to the row's place at
/// the lowest posted there; each none where the mode's carriage is posted at neither end.
#[derive(Clone, Copy, Debug, PartialEq, Eq)]
pub struct Away {
    pub zone: u32,
    pub mode: u16,
    pub metres: u64,
    pub there: i64,
    pub outbound: Missing<i64>,
    pub inbound: Missing<i64>,
}

/// What a row's party may read of goods beyond its facts: its free units of each good at its place, those not pledged or
/// committed, and the list of them; the deposits whose rights it holds; the units of a product, of every grade, it has
/// delivered since the world opened; and each good's latest mark at its place and the public outlook of its price
/// there by a method, which are public.
pub trait GoodsView: core::fmt::Debug {
    fn held(&self, slot: Slot, product: u16, grade: u8) -> i64;
    fn goods(&self, slot: Slot) -> &[HeldGood];
    fn rights(&self, slot: Slot) -> &[HeldRight];
    fn delivered(&self, slot: Slot, product: u16) -> i64;
    fn mark(&self, slot: Slot, product: u16, grade: u8) -> Missing<i64>;
    /// The price a product last sold at, for a lot, at retail in the row's country: the market's mark.
    fn posted(&self, slot: Slot, product: u16) -> Missing<i64>;
    /// A method's record on the series a stance over a product reads — its market between firms where the row stands,
    /// or else its country's retail market — in millionths; none before the method's first surprise there.
    fn record(&self, slot: Slot, product: u16, method: u16) -> Missing<i64>;
    /// The party the row is, as a subject a draw of its own is keyed by.
    fn party(&self, slot: Slot) -> Missing<phx_id::PartyId>;
    fn outlook(&self, slot: Slot, product: u16, grade: u8, method: u16) -> Missing<i64>;
    /// The money the row's party holds on its account; none without an account.
    fn money(&self, slot: Slot) -> Missing<i64>;
    /// The hours a week the row's party's employees work for it, as its employment lines hold them.
    fn staff_hours(&self, slot: Slot) -> Missing<i64>;
    /// The country the row stands in.
    fn country(&self, slot: Slot) -> Missing<phx_id::CountryId>;
    /// Whether the good's market where the row stands last met with no seller.
    fn unsold(&self, slot: Slot, product: u16, grade: u8) -> bool;
    /// The grade classes a product is marked in at some place, in their order.
    fn grades(&self, product: u16) -> Vec<u8>;
    /// The zone the row stands in.
    fn zone(&self, slot: Slot) -> Missing<u32>;
    /// The goods the row holds at other places than its own.
    fn elsewhere(&self, slot: Slot) -> &[HeldAway];
    /// The plant the row holds.
    fn plant(&self, slot: Slot) -> &[HeldPlant];
    /// The other places in the row's country a good is marked at, by each mode carriage is marked in where it stands.
    fn away(&self, slot: Slot, product: u16, grade: u8) -> Vec<Away>;
    /// What winding the row's party down would return beyond the money it keeps either way: its goods less what it
    /// owes.
    fn net_assets(&self, slot: Slot) -> Missing<i64>;
}

